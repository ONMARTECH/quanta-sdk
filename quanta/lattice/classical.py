"""quanta.lattice.classical — Classical Lattice Reduction and CVP Algorithms.

Implements foundational polynomial-time lattice reduction and heuristic closest vector
algorithms, including the Lenstra-Lenstra-Lovász (LLL) lattice basis reduction algorithm
and Babai's Nearest Plane projection algorithm.
"""

from __future__ import annotations

import numpy as np


def gram_schmidt_orthogonalize(
    basis: np.ndarray,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Computes Gram-Schmidt orthogonal vectors and projection coefficients.

    Given basis B = [b_0, ..., b_{n-1}] in R^(m x n) with columns as basis vectors, computes:
        b_i* = b_i - sum_{j=0}^{i-1} mu_{i, j} b_j*
        mu_{i, j} = <b_i, b_j*> / ||b_j*||^2

    Args:
        basis: Matrix of shape (m, n) with basis vectors as columns.

    Returns:
        Tuple of:
            - b_star: Orthogonal vectors matrix of shape (m, n).
            - mu: Lower-triangular projection coefficients matrix of shape (n, n)
              with unit diagonal.
            - b_star_sqnorms: Squared Euclidean norms ||b_i*||^2 of shape (n,).
    """
    basis_arr = np.asarray(basis, dtype=np.float64)
    m, n = basis_arr.shape
    b_star = np.zeros((m, n), dtype=np.float64)
    mu = np.zeros((n, n), dtype=np.float64)
    b_star_sqnorms = np.zeros(n, dtype=np.float64)

    for i in range(n):
        col = basis_arr[:, i].copy()
        for j in range(i):
            if b_star_sqnorms[j] > 1e-15:
                mu_ij = float(np.dot(col, b_star[:, j]) / b_star_sqnorms[j])
                mu[i, j] = mu_ij
                col -= mu_ij * b_star[:, j]
            else:
                mu[i, j] = 0.0
        b_star[:, i] = col
        b_star_sqnorms[i] = float(np.dot(col, col))
        mu[i, i] = 1.0

    return b_star, mu, b_star_sqnorms


def lll_reduce(
    B: np.ndarray,
    delta: float = 0.75,
) -> tuple[np.ndarray, np.ndarray]:
    """Implements Lenstra-Lenstra-Lovász (LLL) polynomial-time lattice reduction.

    Computes an LLL-reduced basis B_red for the lattice generated by B, along with the
    unimodular transformation matrix U in Z^(n x n) such that B_red = B @ U and |det(U)| = 1.

    The reduced basis satisfies:
        1. Size reduction: |mu_{i, j}| <= 0.5 for all 0 <= j < i < n.
        2. Lovász condition: delta * ||b_{k-1}*||^2 <= ||b_k* + mu_{k, k-1} b_{k-1}*||^2
           for all 1 <= k < n.

    Args:
        B: Input lattice basis of shape (m, n) with columns as basis vectors (m >= n).
        delta: Lovász parameter in (0.25, 1.0). Default is 0.75.

    Returns:
        Tuple of:
            - B_red: Reduced basis matrix of shape (m, n) with basis vectors as columns.
            - U: Unimodular integer transformation matrix in Z^(n x n) satisfying B_red = B @ U.

    Raises:
        ValueError: If delta is outside (0.25, 1.0) or matrix dimensions are invalid.
    """
    if not (0.25 < delta < 1.0):
        raise ValueError(f"Lovász parameter delta must be in (0.25, 1.0), got {delta}.")

    b_arr = np.asarray(B, dtype=np.float64)
    if b_arr.ndim != 2:
        raise ValueError(f"Basis B must be a 2D matrix, got shape {b_arr.shape}.")
    m, n = b_arr.shape
    if m < n:
        raise ValueError(f"Lattice dimension error: rows m ({m}) must be >= columns n ({n}).")

    if n <= 1:
        return b_arr.copy(), np.eye(n, dtype=np.int64)

    b_work = b_arr.copy()
    u_mat = np.eye(n, dtype=np.int64)

    b_star, mu, sqnorms = gram_schmidt_orthogonalize(b_work)
    k = 1

    while k < n:
        # Size reduction of b_k with respect to b_{k-1}
        if abs(mu[k, k - 1]) > 0.5:
            c = int(np.round(mu[k, k - 1]))
            b_work[:, k] -= c * b_work[:, k - 1]
            u_mat[:, k] -= c * u_mat[:, k - 1]
            b_star, mu, sqnorms = gram_schmidt_orthogonalize(b_work)

        # Lovász condition check: delta * ||b_{k-1}*||^2 <= ||b_k*||^2 + mu_{k, k-1}^2 * ||b_{k-1}*||^2
        lovasz_lhs = delta * sqnorms[k - 1]
        lovasz_rhs = sqnorms[k] + (mu[k, k - 1] ** 2) * sqnorms[k - 1]

        if lovasz_rhs >= lovasz_lhs - 1e-12:
            # Size reduce b_k with respect to all preceding basis vectors b_{k-2}, ..., b_0
            for j in range(k - 2, -1, -1):
                if abs(mu[k, j]) > 0.5:
                    c = int(np.round(mu[k, j]))
                    b_work[:, k] -= c * b_work[:, j]
                    u_mat[:, k] -= c * u_mat[:, j]
                    b_star, mu, sqnorms = gram_schmidt_orthogonalize(b_work)
            k += 1
        else:
            # Swap vectors b_{k-1} and b_k
            b_work[:, [k - 1, k]] = b_work[:, [k, k - 1]]
            u_mat[:, [k - 1, k]] = u_mat[:, [k, k - 1]]
            b_star, mu, sqnorms = gram_schmidt_orthogonalize(b_work)
            k = max(k - 1, 1)

    # Final size-reduction polish to ensure all |mu_{i, j}| <= 0.5
    for i in range(1, n):
        for j in range(i - 1, -1, -1):
            if abs(mu[i, j]) > 0.5:
                c = int(np.round(mu[i, j]))
                b_work[:, i] -= c * b_work[:, j]
                u_mat[:, i] -= c * u_mat[:, j]
                b_star, mu, sqnorms = gram_schmidt_orthogonalize(b_work)

    return b_work, u_mat


def babai_nearest_plane(
    B: np.ndarray,
    t: np.ndarray,
    reduce: bool = False,
    delta: float = 0.75,
) -> np.ndarray:
    """Implements Babai's Nearest Plane algorithm to solve the Closest Vector Problem (CVP).

    Given basis B and target t, sequentially projects the residual target onto Gram-Schmidt
    hyperplanes in reverse order (i = n-1, ..., 0) and rounds continuous coordinates to integers.

    Args:
        B: Basis matrix of shape (m, n) with basis vectors as columns.
        t: Target vector of shape (m,).
        reduce: If True, preconditions the basis with LLL reduction before projection,
            then transforms coordinate vector back to original basis coordinates.
        delta: LLL reduction parameter (used when reduce=True).

    Returns:
        Integer coordinate vector z in Z^n such that B @ z is the estimated closest lattice point.
    """
    b_arr = np.asarray(B, dtype=np.float64)
    t_arr = np.asarray(t, dtype=np.float64).reshape(-1)
    m, n = b_arr.shape

    if len(t_arr) != m:
        raise ValueError(f"Target dimension {len(t_arr)} must match basis row dimension {m}.")

    if reduce:
        b_red, u_mat = lll_reduce(b_arr, delta=delta)
        z_red = babai_nearest_plane(b_red, t_arr, reduce=False)
        z_mapped: np.ndarray = np.asarray(u_mat @ z_red, dtype=np.int64)
        return z_mapped

    b_star, _, sqnorms = gram_schmidt_orthogonalize(b_arr)
    b_prime = t_arr.copy()
    z = np.zeros(n, dtype=np.int64)

    for i in range(n - 1, -1, -1):
        c_i = (
            float(np.dot(b_prime, b_star[:, i]) / sqnorms[i])
            if sqnorms[i] > 1e-15
            else 0.0
        )
        z_i = int(np.round(c_i))
        z[i] = z_i
        b_prime -= z_i * b_arr[:, i]

    return z


def solve_cvp_classical(
    B: np.ndarray,
    t: np.ndarray,
    delta: float = 0.75,
) -> tuple[np.ndarray, float]:
    """Convenience solver for classical CVP via LLL preconditioning and Babai Nearest Plane.

    Args:
        B: Basis matrix of shape (m, n) with basis vectors as columns.
        t: Target vector of shape (m,).
        delta: Lovász parameter for LLL reduction.

    Returns:
        Tuple of:
            - z: Optimal integer coordinates in Z^n.
            - distance: Euclidean residual distance ||B @ z - t||_2.
    """
    b_arr = np.asarray(B, dtype=np.float64)
    t_arr = np.asarray(t, dtype=np.float64).reshape(-1)
    z = babai_nearest_plane(b_arr, t_arr, reduce=True, delta=delta)
    lattice_point = b_arr @ z.astype(np.float64)
    dist = float(np.linalg.norm(lattice_point - t_arr))
    return z, dist
